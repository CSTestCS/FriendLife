const { chromium } = require('playwright');
const http = require('node:http'); const fs = require('node:fs'); const path = require('node:path');
const base = path.join(__dirname, '..');
const server = http.createServer((req, res) => { const u = decodeURIComponent(req.url.split('?')[0]); const p = u.startsWith('/test-samples/') ? path.join(base, 'samples/test', u.slice(14)) : path.join(base, 'dist', u === '/' ? 'index.html' : u); if (!fs.existsSync(p)) { res.writeHead(404); return res.end(); } res.writeHead(200, { 'content-type': p.endsWith('.html') ? 'text/html' : p.endsWith('.js') ? 'text/javascript' : 'application/octet-stream' }); fs.createReadStream(p).pipe(res); });
(async () => {
  await new Promise((r) => server.listen(5193, r));
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage();
  await page.goto('http://localhost:5193/'); await page.waitForSelector('#titleButtons button'); await page.click('#titleButtons button');
  await page.waitForFunction(() => window.__friendlife?.sim?.residents?.length >= 6, null, { timeout: 60000 });
  const out = await page.evaluate(async () => {
    const app = window.__friendlife; const s = app.sim; const lib = s.library;
    const get = async (f) => (await fetch(`/samples/${encodeURIComponent(f)}`)).arrayBuffer();
    const of = await lib.add({ name: 'H', type: 'outfit', data: await get('Sample Hoodie Outfit.vrm'), ext: 'vrm' });
    const r = s.residents[0];
    r.d.outfits = [{ name: 'Hoodie', look: null, outfit: { assetId: of.id, parts: null }, tags: [], perception: { self: [], others: [] } }];
    const gl = app.stage.renderer.getContext();
    const stacks = [];
    const orig = gl.createTexture.bind(gl);
    gl.createTexture = () => { stacks.push('create'); return orig(); };
    const ti = gl.texImage2D.bind(gl), ts = gl.texStorage2D.bind(gl);
    gl.texImage2D = (...a) => { const src = a.find((x) => x && typeof x === 'object' && 'width' in x); stacks.push('img ' + (src ? src.constructor.name + ' ' + src.width + 'x' + src.height : a.slice(3, 5).join('x'))); return ti(...a); };
    gl.texStorage2D = (...a) => { stacks.push('storage ' + a[3] + 'x' + a[4]); return ts(...a); };
    const raf = () => new Promise((q) => requestAnimationFrame(q));
    await s.changeOutfit(r, 0, { quiet: true }); await raf(); await raf(); await raf();
    gl.createTexture = orig; gl.texImage2D = ti; gl.texStorage2D = ts;
    const list = [];
    r.avatar.root.traverse((o) => { if (!o.isMesh) return; for (const m of [].concat(o.material)) { for (const [k, u] of Object.entries(m.uniforms || {})) { const t = u.value; if (t?.isTexture) list.push(k + ' ' + (t.name || '') + ' ' + (t.image?.width || '?') + 'x' + (t.image?.height || '?') + ' src=' + t.source.uuid.slice(0, 5) + ' ' + t.constructor.name); } } });
    return [stacks.join(' | '), ...new Set(list)];
  });
  console.log(out.join('\n\n'));
  await browser.close(); server.close();
})();
